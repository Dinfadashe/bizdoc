const fs = require('fs');

const content = [
'import { NextRequest, NextResponse } from "next/server";',
'import { supabaseAdmin } from "@/lib/supabase";',
'import { calcTotals, generateInvoiceNumber } from "@/lib/utils";',
'',
'export async function POST(req: NextRequest) {',
'  try {',
'    const body = await req.json();',
'    const {',
'      user_id, client_name, client_email, client_phone, client_address,',
'      items = [], discount_type = "percent", discount_value = 0, tax_rate = 0,',
'      notes, issue_date, due_date, currency = "NGN", display_account_id,',
'    } = body;',
'',
'    if (!user_id) return NextResponse.json({ error: "user_id required" }, { status: 400 });',
'',
'    const { subtotal, discountAmount, taxAmount, total } = calcTotals(items, discount_type, discount_value, tax_rate);',
'    const today = new Date().toISOString().split("T")[0];',
'    const tomorrow = new Date(Date.now() + 24*60*60*1000).toISOString().split("T")[0];',
'',
'    const { data, error } = await supabaseAdmin.from("invoices").insert({',
'      user_id,',
'      invoice_number: generateInvoiceNumber(),',
'      status: "draft",',
'      currency,',
'      client_name: client_name || null,',
'      client_email: client_email || null,',
'      client_phone: client_phone || null,',
'      client_address: client_address || null,',
'      items,',
'      discount_type, discount_value,',
'      discount_amount: discountAmount,',
'      tax_rate, tax_amount: taxAmount,',
'      subtotal, total, notes,',
'      issue_date: issue_date || today,',
'      due_date: due_date || tomorrow,',
'      display_account_id: display_account_id || null,',
'    }).select().single();',
'',
'    if (error) throw error;',
'',
'    // Auto-add to catalog',
'    if (items.length > 0) {',
'      const { data: existing } = await supabaseAdmin.from("catalog").select("name").eq("user_id", user_id);',
'      const existingNames = new Set((existing ?? []).map((c: any) => c.name.toLowerCase().trim()));',
'      const newItems = items.filter((i: any) => i.description && i.description.trim() && !existingNames.has(i.description.toLowerCase().trim()))',
'        .map((i: any) => ({ user_id, name: i.description.trim(), description: "", unit_price: i.unit_price ?? 0 }));',
'      if (newItems.length > 0) { try { await supabaseAdmin.from("catalog").insert(newItems); } catch(_) {} }',
'    }',
'',
'    return NextResponse.json({ invoice: data });',
'  } catch (err: unknown) {',
'    console.error("Invoice creation error:", err);',
'    return NextResponse.json({ error: err instanceof Error ? err.message : "Unknown error" }, { status: 500 });',
'  }',
'}',
].join('\n');

fs.writeFileSync('app/api/invoices/route.ts', content, { encoding: 'utf8' });
console.log('Done invoice API');