const fs = require('fs');

// ── 1. Business Accounts API ─────────────────────────────────
fs.mkdirSync('app/api/business-accounts', { recursive: true });
fs.writeFileSync('app/api/business-accounts/route.ts', [
'import { NextRequest, NextResponse } from "next/server";',
'import { supabaseAdmin } from "@/lib/supabase";',
'',
'export async function GET(req: NextRequest) {',
'  const { searchParams } = new URL(req.url);',
'  const user_id = searchParams.get("user_id");',
'  if (!user_id) return NextResponse.json({ error: "user_id required" }, { status: 400 });',
'  const { data } = await supabaseAdmin.from("business_accounts").select("*").eq("user_id", user_id).order("created_at");',
'  return NextResponse.json({ accounts: data ?? [] });',
'}',
'',
'export async function POST(req: NextRequest) {',
'  try {',
'    const { user_id, account_name, account_number, bank_name, currency, is_default } = await req.json();',
'    if (!user_id || !account_name || !account_number || !bank_name) {',
'      return NextResponse.json({ error: "Missing required fields" }, { status: 400 });',
'    }',
'    if (is_default) {',
'      await supabaseAdmin.from("business_accounts").update({ is_default: false }).eq("user_id", user_id);',
'    }',
'    const { data, error } = await supabaseAdmin.from("business_accounts").insert({',
'      user_id, account_name, account_number, bank_name, currency: currency || "NGN", is_default: is_default || false',
'    }).select().single();',
'    if (error) throw error;',
'    return NextResponse.json({ account: data });',
'  } catch (err: unknown) {',
'    return NextResponse.json({ error: err instanceof Error ? err.message : "Error" }, { status: 500 });',
'  }',
'}',
'',
'export async function DELETE(req: NextRequest) {',
'  const { searchParams } = new URL(req.url);',
'  const id = searchParams.get("id");',
'  if (!id) return NextResponse.json({ error: "id required" }, { status: 400 });',
'  await supabaseAdmin.from("business_accounts").delete().eq("id", id);',
'  return NextResponse.json({ ok: true });',
'}',
].join('\n'), { encoding: 'utf8' });
console.log('Created business-accounts API');

// ── 2. Subscription API ──────────────────────────────────────
fs.mkdirSync('app/api/subscription', { recursive: true });
fs.writeFileSync('app/api/subscription/route.ts', [
'import { NextRequest, NextResponse } from "next/server";',
'import { supabaseAdmin } from "@/lib/supabase";',
'',
'export async function GET(req: NextRequest) {',
'  const { searchParams } = new URL(req.url);',
'  const user_id = searchParams.get("user_id");',
'  if (!user_id) return NextResponse.json({ error: "user_id required" }, { status: 400 });',
'  const { data } = await supabaseAdmin.from("subscriptions").select("*").eq("user_id", user_id).single();',
'  if (!data) {',
'    // Create trial if not exists',
'    const { data: newSub } = await supabaseAdmin.from("subscriptions").insert({',
'      user_id, status: "trial", trial_ends_at: new Date(Date.now() + 30 * 24 * 60 * 60 * 1000).toISOString()',
'    }).select().single();',
'    return NextResponse.json({ subscription: newSub });',
'  }',
'  return NextResponse.json({ subscription: data });',
'}',
].join('\n'), { encoding: 'utf8' });
console.log('Created subscription API');

// ── 3. Subscription webhook ──────────────────────────────────
fs.mkdirSync('app/api/subscription/activate', { recursive: true });
fs.writeFileSync('app/api/subscription/activate/route.ts', [
'import { NextRequest, NextResponse } from "next/server";',
'import { supabaseAdmin } from "@/lib/supabase";',
'import crypto from "crypto";',
'',
'export async function POST(req: NextRequest) {',
'  const rawBody = await req.text();',
'  const signature = req.headers.get("x-paystack-signature") ?? "";',
'  const secret = process.env.PAYSTACK_SECRET_KEY!;',
'  const hash = crypto.createHmac("sha512", secret).update(rawBody).digest("hex");',
'  if (hash !== signature) return NextResponse.json({ error: "Invalid signature" }, { status: 401 });',
'',
'  const event = JSON.parse(rawBody);',
'  if (event.event === "charge.success") {',
'    const { reference, metadata } = event.data;',
'    const user_id = metadata?.user_id;',
'    const plan = metadata?.plan ?? "monthly";',
'    if (!user_id) return NextResponse.json({ ok: true });',
'',
'    const months = plan === "annual" ? 12 : 1;',
'    const expires_at = new Date(Date.now() + months * 30 * 24 * 60 * 60 * 1000).toISOString();',
'',
'    await supabaseAdmin.from("subscriptions").upsert({',
'      user_id,',
'      status: "active",',
'      plan,',
'      subscribed_at: new Date().toISOString(),',
'      expires_at,',
'      paystack_reference: reference,',
'    }, { onConflict: "user_id" });',
'',
'    console.log("Subscription activated for:", user_id, "plan:", plan, "expires:", expires_at);',
'  }',
'  return NextResponse.json({ ok: true });',
'}',
'',
'export const config = { api: { bodyParser: false } };',
].join('\n'), { encoding: 'utf8' });
console.log('Created subscription activate webhook');

