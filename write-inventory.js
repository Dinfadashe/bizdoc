const fs = require('fs');

// ── 1. Inventory API ─────────────────────────────────────────
fs.mkdirSync('app/api/inventory', { recursive: true });
fs.writeFileSync('app/api/inventory/route.ts', [
'import { NextRequest, NextResponse } from "next/server";',
'import { supabaseAdmin } from "@/lib/supabase";',
'',
'export async function GET(req: NextRequest) {',
'  const { searchParams } = new URL(req.url);',
'  const user_id = searchParams.get("user_id");',
'  if (!user_id) return NextResponse.json({ error: "user_id required" }, { status: 400 });',
'  const { data } = await supabaseAdmin.from("inventory").select("*").eq("user_id", user_id).order("name");',
'  return NextResponse.json({ inventory: data ?? [] });',
'}',
'',
'export async function POST(req: NextRequest) {',
'  try {',
'    const body = await req.json();',
'    const { user_id, name, description, sku, category, cost_price, selling_price, quantity, low_stock_alert, unit } = body;',
'    if (!user_id || !name) return NextResponse.json({ error: "user_id and name required" }, { status: 400 });',
'    const { data, error } = await supabaseAdmin.from("inventory").insert({',
'      user_id, name, description, sku, category, cost_price: cost_price || 0,',
'      selling_price: selling_price || 0, quantity: quantity || 0,',
'      low_stock_alert: low_stock_alert || 5, unit: unit || "unit"',
'    }).select().single();',
'    if (error) throw error;',
'    // Log stock movement if initial quantity > 0',
'    if (quantity > 0) {',
'      await supabaseAdmin.from("stock_movements").insert({',
'        user_id, inventory_id: data.id, type: "in", quantity, reference: "Initial stock", note: "Opening stock"',
'      });',
'    }',
'    return NextResponse.json({ item: data });',
'  } catch (err: unknown) {',
'    return NextResponse.json({ error: err instanceof Error ? err.message : "Error" }, { status: 500 });',
'  }',
'}',
'',
'export async function PATCH(req: NextRequest) {',
'  try {',
'    const body = await req.json();',
'    const { id, ...updates } = body;',
'    if (!id) return NextResponse.json({ error: "id required" }, { status: 400 });',
'    const { data, error } = await supabaseAdmin.from("inventory").update({ ...updates, updated_at: new Date().toISOString() }).eq("id", id).select().single();',
'    if (error) throw error;',
'    return NextResponse.json({ item: data });',
'  } catch (err: unknown) {',
'    return NextResponse.json({ error: err instanceof Error ? err.message : "Error" }, { status: 500 });',
'  }',
'}',
'',
'export async function DELETE(req: NextRequest) {',
'  const { searchParams } = new URL(req.url);',
'  const id = searchParams.get("id");',
'  if (!id) return NextResponse.json({ error: "id required" }, { status: 400 });',
'  await supabaseAdmin.from("inventory").delete().eq("id", id);',
'  return NextResponse.json({ ok: true });',
'}',
].join('\n'), { encoding: 'utf8' });
console.log('Created inventory API');

// ── 2. Stock Movement API ─────────────────────────────────────
fs.mkdirSync('app/api/inventory/stock', { recursive: true });
fs.writeFileSync('app/api/inventory/stock/route.ts', [
'import { NextRequest, NextResponse } from "next/server";',
'import { supabaseAdmin } from "@/lib/supabase";',
'',
'export async function POST(req: NextRequest) {',
'  try {',
'    const { user_id, inventory_id, type, quantity, reference, note } = await req.json();',
'    if (!user_id || !inventory_id || !type || !quantity) {',
'      return NextResponse.json({ error: "Missing required fields" }, { status: 400 });',
'    }',
'    // Update inventory quantity',
'    const { data: item } = await supabaseAdmin.from("inventory").select("quantity").eq("id", inventory_id).single();',
'    if (!item) return NextResponse.json({ error: "Item not found" }, { status: 404 });',
'    const newQty = type === "in" ? Number(item.quantity) + Number(quantity) : Math.max(0, Number(item.quantity) - Number(quantity));',
'    await supabaseAdmin.from("inventory").update({ quantity: newQty, updated_at: new Date().toISOString() }).eq("id", inventory_id);',
'    // Log movement',
'    const { data: movement } = await supabaseAdmin.from("stock_movements").insert({',
'      user_id, inventory_id, type, quantity, reference, note',
'    }).select().single();',
'    return NextResponse.json({ movement, new_quantity: newQty });',
'  } catch (err: unknown) {',
'    return NextResponse.json({ error: err instanceof Error ? err.message : "Error" }, { status: 500 });',
'  }',
'}',
'',
'export async function GET(req: NextRequest) {',
'  const { searchParams } = new URL(req.url);',
'  const inventory_id = searchParams.get("inventory_id");',
'  const user_id = searchParams.get("user_id");',
'  if (!user_id) return NextResponse.json({ error: "user_id required" }, { status: 400 });',
'  let query = supabaseAdmin.from("stock_movements").select("*").eq("user_id", user_id).order("created_at", { ascending: false }).limit(50);',
'  if (inventory_id) query = query.eq("inventory_id", inventory_id);',
'  const { data } = await query;',
'  return NextResponse.json({ movements: data ?? [] });',
'}',
].join('\n'), { encoding: 'utf8' });
console.log('Created stock movement API');

// ── 3. Expenses API ──────────────────────────────────────────
fs.mkdirSync('app/api/expenses', { recursive: true });
fs.writeFileSync('app/api/expenses/route.ts', [
'import { NextRequest, NextResponse } from "next/server";',
'import { supabaseAdmin } from "@/lib/supabase";',
'',
'export async function GET(req: NextRequest) {',
'  const { searchParams } = new URL(req.url);',
'  const user_id = searchParams.get("user_id");',
'  const from = searchParams.get("from");',
'  const to = searchParams.get("to");',
'  if (!user_id) return NextResponse.json({ error: "user_id required" }, { status: 400 });',
'  let query = supabaseAdmin.from("expenses").select("*").eq("user_id", user_id).order("date", { ascending: false });',
'  if (from) query = query.gte("date", from);',
'  if (to) query = query.lte("date", to);',
'  const { data } = await query;',
'  return NextResponse.json({ expenses: data ?? [] });',
'}',
'',
'export async function POST(req: NextRequest) {',
'  try {',
'    const { user_id, added_by, title, category, amount, currency, date, note } = await req.json();',
'    if (!user_id || !title || !amount) return NextResponse.json({ error: "Missing required fields" }, { status: 400 });',
'    const { data, error } = await supabaseAdmin.from("expenses").insert({',
'      user_id, added_by: added_by || user_id, title, category: category || "Other",',
'      amount, currency: currency || "NGN", date: date || new Date().toISOString().split("T")[0], note',
'    }).select().single();',
'    if (error) throw error;',
'    return NextResponse.json({ expense: data });',
'  } catch (err: unknown) {',
'    return NextResponse.json({ error: err instanceof Error ? err.message : "Error" }, { status: 500 });',
'  }',
'}',
'',
'export async function DELETE(req: NextRequest) {',
'  const { searchParams } = new URL(req.url);',
'  const id = searchParams.get("id");',
'  if (!id) return NextResponse.json({ error: "id required" }, { status: 400 });',
'  await supabaseAdmin.from("expenses").delete().eq("id", id);',
'  return NextResponse.json({ ok: true });',
'}',
].join('\n'), { encoding: 'utf8' });
console.log('Created expenses API');

// ── 4. Stats API ─────────────────────────────────────────────
fs.mkdirSync('app/api/stats', { recursive: true });
fs.writeFileSync('app/api/stats/route.ts', [
'import { NextRequest, NextResponse } from "next/server";',
'import { supabaseAdmin } from "@/lib/supabase";',
'',
'export async function GET(req: NextRequest) {',
'  const { searchParams } = new URL(req.url);',
'  const user_id = searchParams.get("user_id");',
'  const year = searchParams.get("year") || new Date().getFullYear().toString();',
'  if (!user_id) return NextResponse.json({ error: "user_id required" }, { status: 400 });',
'',
'  const [invoicesRes, expensesRes, inventoryRes] = await Promise.all([',
'    supabaseAdmin.from("invoices").select("total,status,currency,paid_at,created_at,items").eq("user_id", user_id),',
'    supabaseAdmin.from("expenses").select("amount,currency,date,category").eq("user_id", user_id),',
'    supabaseAdmin.from("inventory").select("id,name,quantity,cost_price,selling_price,low_stock_alert").eq("user_id", user_id),',
'  ]);',
'',
'  const invoices = invoicesRes.data ?? [];',
'  const expenses = expensesRes.data ?? [];',
'  const inventory = inventoryRes.data ?? [];',
'',
'  // Revenue from paid invoices this year',
'  const paidInvoices = invoices.filter((i: any) => i.status === "paid" && i.paid_at && new Date(i.paid_at).getFullYear().toString() === year);',
'  const totalRevenue = paidInvoices.reduce((sum: number, i: any) => sum + Number(i.total), 0);',
'',
'  // Total expenses this year',
'  const yearExpenses = expenses.filter((e: any) => e.date && new Date(e.date).getFullYear().toString() === year);',
'  const totalExpenses = yearExpenses.reduce((sum: number, e: any) => sum + Number(e.amount), 0);',
'',
'  // Monthly breakdown',
'  const months = Array.from({ length: 12 }, (_, i) => ({',
'    month: i + 1,',
'    label: new Date(2000, i).toLocaleString("default", { month: "short" }),',
'    revenue: 0,',
'    expenses: 0,',
'  }));',
'',
'  paidInvoices.forEach((inv: any) => {',
'    const m = new Date(inv.paid_at).getMonth();',
'    months[m].revenue += Number(inv.total);',
'  });',
'',
'  yearExpenses.forEach((exp: any) => {',
'    const m = new Date(exp.date).getMonth();',
'    months[m].expenses += Number(exp.amount);',
'  });',
'',
'  // Expense by category',
'  const expenseByCategory: Record<string, number> = {};',
'  yearExpenses.forEach((e: any) => {',
'    expenseByCategory[e.category] = (expenseByCategory[e.category] || 0) + Number(e.amount);',
'  });',
'',
'  // Outstanding invoices',
'  const outstanding = invoices.filter((i: any) => i.status === "sent" || i.status === "draft");',
'  const totalOutstanding = outstanding.reduce((sum: number, i: any) => sum + Number(i.total), 0);',
'',
'  // Low stock items',
'  const lowStock = inventory.filter((i: any) => Number(i.quantity) <= Number(i.low_stock_alert));',
'',
'  // Inventory value',
'  const inventoryValue = inventory.reduce((sum: number, i: any) => sum + Number(i.quantity) * Number(i.cost_price), 0);',
'',
'  // Top selling products from invoice items',
'  const productSales: Record<string, { qty: number; revenue: number }> = {};',
'  paidInvoices.forEach((inv: any) => {',
'    if (Array.isArray(inv.items)) {',
'      inv.items.forEach((item: any) => {',
'        if (!item.description) return;',
'        if (!productSales[item.description]) productSales[item.description] = { qty: 0, revenue: 0 };',
'        productSales[item.description].qty += Number(item.qty) || 0;',
'        productSales[item.description].revenue += (Number(item.qty) || 0) * (Number(item.unit_price) || 0);',
'      });',
'    }',
'  });',
'  const topProducts = Object.entries(productSales)',
'    .map(([name, data]) => ({ name, ...data }))',
'    .sort((a, b) => b.revenue - a.revenue)',
'    .slice(0, 5);',
'',
'  return NextResponse.json({',
'    totalRevenue, totalExpenses,',
'    grossProfit: totalRevenue - totalExpenses,',
'    totalOutstanding,',
'    invoiceCount: invoices.length,',
'    paidCount: paidInvoices.length,',
'    months,',
'    expenseByCategory,',
'    lowStock,',
'    inventoryValue,',
'    topProducts,',
'  });',
'}',
].join('\n'), { encoding: 'utf8' });
console.log('Created stats API');

console.log('All APIs created!');